from pathlib import Path

csv.field_size_limit(sys.maxsize)

WATERMARK_RE = re.compile(r"\b[a-z]{2}\d{3}k\d+k\d+r\d+\b", re.I)
USE_USE_RE = re.compile(r"\buse use\b", re.I)
AREA_AREA_RE = re.compile(r"\barea area\b", re.I)
SLOT_DESERVES_RE = re.compile(
    r"When ([^<]{3,80}) deserves a closer look", re.I
)
PLURAL_SLOT_RE = re.compile(
    r"When (?:underwriting questions|related next steps|avoidable missteps|"
    r"supporting records|accuracy and dispute preparation|reported balances and utilization|"
    r"promises of guaranteed deletions) deserves\b",
    re.I,
)
AI_LEAK_RE = re.compile(
    r"\b(?:as an AI(?: language model)?|as a language model|I(?:'m| am) an AI|"
    r"I cannot (?:provide|browse)|ChatGPT(?!-Image)|generated by (?:an )?AI)\b",
    re.I,
)
HARD_GUARANTEE_RE = re.compile(
    r"\b(?:we (?:guarantee|will (?:remove|delete|erase) (?:all|every|your))|"
    r"100% guaranteed)\b",
    re.I,
)
DISCLAIMER_GUARANTEE_RE = re.compile(
    r"\b(?:no[^.]{0,40}guarantee|not (?:a |an )?(?:guarantee|guaranteed)|"
    r"cannot guarantee|should not guarantee|reject guaranteed|"
    r"avoid implying[^.]{0,40}guaranteed|promises of guaranteed)\b",
    re.I,
)
TRUNC_META_RE = re.compile(
    r"(?:\s(?:re|a|the|and|for|to|of|in|inf|s)\.?)$", re.I
)
PHONE_RE = re.compile(
    r"\b(?:\+?1[-. ]?)?(?:\(?\d{3}\)?[-. ]?)\d{3}[-. ]?\d{4}\b"
)
ACCOUNT_RE = re.compile(r"\baccount\s+\d{3,5}\b", re.I)
DATE_RE = re.compile(
    r"\b(?:January|February|March|April|May|June|July|August|September|"
    r"October|November|December)\s+\d{1,2},\s+\d{4}\b"
)
MONEY_RE = re.compile(r"\$[\d,]+(?:\.\d{2})?")
TAG_RE = re.compile(r"<[^>]+>")
WS_RE = re.compile(r"\s+")

PROTECTED_SEQUENCES = {1, 2, 3, 4, 5}
DEFAULT_CORPUS_CANDIDATES = [
    Path("/tmp/uniqueness_corpus"),
    Path("CHATGPT_BATCH_INTAKE/UNIQUENESS_CORPUS"),
    Path("D:/CHATGPT_BATCH_INTAKE/UNIQUENESS_CORPUS"),
    Path("D:/Superior Credit Rebuild/CHATGPT_BATCH_INTAKE/UNIQUENESS_CORPUS"),
]


class PageHTMLParser(HTMLParser):
    def __init__(self) -> None:
        super().__init__()
        self.parts: list[str] = []
        self.h2: list[str] = []
        self.skip = False
        self._h2 = False

    def handle_starttag(self, tag: str, attrs) -> None:
        if tag in {"script", "style"}:
            self.skip = True
        if tag == "h2":
            self._h2 = True

    def handle_endtag(self, tag: str) -> None:
        if tag in {"script", "style"}:
            self.skip = False
        if tag == "h2":
            self._h2 = False

    def handle_data(self, data: str) -> None:
        if self.skip:
            return
        self.parts.append(data)
        if self._h2:
            self.h2.append(data)


def strip_text(html: str) -> tuple[str, list[str]]:
    parser = PageHTMLParser()
    try:
        parser.feed(html)
    except Exception:
        text = WS_RE.sub(" ", TAG_RE.sub(" ", html)).strip()
        return text, []
    text = WS_RE.sub(" ", " ".join(parser.parts)).strip()
    h2s = [WS_RE.sub(" ", h).strip() for h in parser.h2 if h.strip()]
    return text, h2s


def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8", "replace")).hexdigest()


def words_of(text: str) -> list[str]:
    return re.findall(r"[a-z0-9']+", text.lower())


def h2_skeleton(h2s: list[str]) -> str:
    joined = " | ".join(h2s)
    joined = ACCOUNT_RE.sub("account N", joined)
    joined = DATE_RE.sub("DATE", joined)
    joined = MONEY_RE.sub("$N", joined)
    joined = re.sub(r"\b\d+\b", "N", joined)
    return joined.lower()


def minhash(shingles: list[str], num: int = 64) -> tuple[int, ...]:
    mins = [2**64 - 1] * num
    if not shingles:
        return tuple(mins)
    salts = [i * 0x9E3779B97F4A7C15 & 0xFFFFFFFFFFFFFFFF for i in range(num)]
    for shingle in shingles:
        base = int.from_bytes(
            hashlib.blake2b(shingle.encode("utf-8"), digest_size=8).digest(),
            "little",
        )
        for i, salt in enumerate(salts):
            hv = base ^ salt
            if hv < mins[i]:
                mins[i] = hv
    return tuple(mins)


def estimated_jaccard(a: tuple[int, ...], b: tuple[int, ...]) -> float:
    if not a or not b:
        return 0.0
    return sum(x == y for x, y in zip(a, b)) / len(a)


def lsh_bands(sig: tuple[int, ...], bands: int = 16) -> list[tuple[int, tuple[int, ...]]]:
    rows = len(sig) // bands
    out = []
    for i in range(bands):
        chunk = sig[i * rows : (i + 1) * rows]
        out.append((i, chunk))
    return out


@dataclass
class Page:
    slug: str
    title: str
    meta: str
    wp_id: str
    sequence: str
    kind: str
    page_set: str
    store: str
    html: str
    text: str = ""
    h2s: list[str] = field(default_factory=list)
    words: list[str] = field(default_factory=list)
    text_hash: str = ""
    html_hash: str = ""
    h2_hash: str = ""
    minhash: tuple[int, ...] = ()
    flags: list[str] = field(default_factory=list)

    @property
    def seq_int(self) -> int | None:
        if not (self.sequence or "").strip():
            return None
        try:
            return int(self.sequence.strip())
        except ValueError:
            return None


def find_corpus_dir(explicit: str | None) -> Path:
    if explicit:
        path = Path(explicit)
        if not path.exists():
            raise SystemExit(f"Corpus directory not found: {path}")
        return path
    for candidate in DEFAULT_CORPUS_CANDIDATES:
        if candidate.exists() and any(candidate.glob("UNIQUENESS_CORPUS_*_OF_08.csv")):
            return candidate
    raise SystemExit(
        "Could not find UNIQUENESS_CORPUS_*_OF_08.csv. "
        "Pass --corpus-dir to the folder that contains the 8 CSV files."
    )


def load_pages(corpus_dir: Path) -> list[Page]:
    files = sorted(corpus_dir.glob("UNIQUENESS_CORPUS_*_OF_08.csv"))
    if len(files) != 8:
        raise SystemExit(f"Expected 8 corpus CSVs in {corpus_dir}, found {len(files)}")
    pages: list[Page] = []
    for fp in files:
        with fp.open(newline="", encoding="utf-8", errors="replace") as handle:
            for row in csv.DictReader(handle):
                html = row.get("page_html") or ""
                text, h2s = strip_text(html)
                page = Page(
                    slug=row.get("slug") or "",
                    title=row.get("page_title") or "",
                    meta=row.get("meta_description") or "",
                    wp_id=row.get("wordpress_page_id") or "",
                    sequence=row.get("sequence") or "",
                    kind=row.get("kind") or "(blank)",
                    page_set=row.get("page_set") or "(blank)",
                    store=row.get("store") or "(blank)",
                    html=html,
                    text=text,
                    h2s=h2s,
                    words=words_of(text),
                )
                page.text_hash = sha256_text(WS_RE.sub(" ", text.lower()))
                page.html_hash = sha256_text(html)
                page.h2_hash = sha256_text(h2_skeleton(h2s))
                shingles = [
                    " ".join(page.words[i : i + 8])
                    for i in range(0, max(0, len(page.words) - 7), 3)
                ]
                page.minhash = minhash(shingles)
                pages.append(page)
    return pages


def flag_pages(pages: list[Page]) -> None:
    for page in pages:
        if page.seq_int in PROTECTED_SEQUENCES:
            page.flags.append("PROTECTED_SEQUENCE_1_5")
        if page.kind == "CLEARED_PRODUCTION":
            page.flags.append("CLEARED_DO_NOT_OVERWRITE")
        if not page.meta.strip():
            page.flags.append("MISSING_META")
        elif TRUNC_META_RE.search(page.meta.strip()) or (
            148 <= len(page.meta) <= 165 and not page.meta.rstrip().endswith((".", "!", "?"))
        ):
            page.flags.append("TRUNCATED_META")
        if WATERMARK_RE.search(page.html):
            page.flags.append("WATERMARK_TOKENS")
        if USE_USE_RE.search(page.html + " " + page.meta):
            page.flags.append("USE_USE_TYPO")
        if AREA_AREA_RE.search(page.html + " " + page.meta + " " + page.title):
            page.flags.append("AREA_AREA_TYPO")
        if PLURAL_SLOT_RE.search(page.html):
            page.flags.append("SLOT_SUBJECT_VERB")
        if AI_LEAK_RE.search(page.html) or AI_LEAK_RE.search(page.title) or AI_LEAK_RE.search(page.meta):
            page.flags.append("AI_LEAKAGE")
        if HARD_GUARANTEE_RE.search(page.html) and not DISCLAIMER_GUARANTEE_RE.search(page.html):
            page.flags.append("HARD_GUARANTEE")
        if len(page.words) < 800:
            page.flags.append("THIN_WORDCOUNT")
        if len(page.title) < 20:
            page.flags.append("SHORT_TITLE")


def cluster_by(pages: list[Page], attr: str) -> dict[str, list[Page]]:
    groups: dict[str, list[Page]] = defaultdict(list)
    for page in pages:
        groups[getattr(page, attr)].append(page)
    return {key: value for key, value in groups.items() if len(value) > 1}


def near_duplicate_pairs(pages: list[Page], threshold: float = 0.82) -> list[tuple[float, Page, Page]]:
    buckets: dict[tuple[int, tuple[int, ...]], list[int]] = defaultdict(list)
    for idx, page in enumerate(pages):
        for band in lsh_bands(page.minhash):
            buckets[band].append(idx)
    seen: set[tuple[int, int]] = set()
    pairs: list[tuple[float, Page, Page]] = []
    for members in buckets.values():
        if len(members) < 2:
            continue
        uniq = sorted(set(members))
        if len(uniq) > 80:
            continue
        for i, left in enumerate(uniq):
            for right in uniq[i + 1 :]:
                key = (left, right)
                if key in seen:
                    continue
                seen.add(key)
                score = estimated_jaccard(pages[left].minhash, pages[right].minhash)
                if score >= threshold:
                    pairs.append((score, pages[left], pages[right]))
    pairs.sort(key=lambda item: item[0], reverse=True)
    return pairs


def frequent_shingles(pages: list[Page], n: int = 10, min_pages: int = 40, limit: int = 40) -> list[tuple[int, str]]:
    hashed: Counter[bytes] = Counter()
    examples: dict[bytes, str] = {}
    for page in pages:
        local = set()
        words = page.words
        for i in range(0, max(0, len(words) - n + 1), 2):
            shingle = " ".join(words[i : i + n])
            digest = hashlib.blake2b(shingle.encode(), digest_size=8).digest()
            if digest not in local:
                local.add(digest)
                hashed[digest] += 1
                if digest not in examples:
                    examples[digest] = shingle
    top = [(count, examples[digest]) for digest, count in hashed.most_common(300) if count >= min_pages]
    return top[:limit]


def write_csv(path: Path, rows: list[dict], fieldnames: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def summarize(pages: list[Page], pairs: list[tuple[float, Page, Page]], boilerplate: list[tuple[int, str]], out_dir: Path) -> dict:
    kinds = Counter(page.kind for page in pages)
    stores = Counter(page.store for page in pages)
    flags = Counter(flag for page in pages for flag in page.flags)
    title_clusters = cluster_by(pages, "title")
    text_clusters = cluster_by(pages, "text_hash")
    html_clusters = cluster_by(pages, "html_hash")
    h2_clusters = cluster_by(pages, "h2_hash")
    word_counts = sorted(len(page.words) for page in pages)
    n = len(pages)
    phones = Counter()
    slot_h2 = Counter()
    watermark_pages = []
    for page in pages:
        for match in PHONE_RE.findall(page.html):
            phones[match] += 1
        for match in SLOT_DESERVES_RE.findall(page.html):
            slot_h2[WS_RE.sub(" ", match).strip()[:90]] += 1
        if "WATERMARK_TOKENS" in page.flags:
            watermark_pages.append(
                {
                    "slug": page.slug,
                    "kind": page.kind,
                    "sequence": page.sequence,
                    "token_count": len(WATERMARK_RE.findall(page.html)),
                    "title": page.title,
                }
            )

    flag_rows = []
    for page in pages:
        if page.flags:
            flag_rows.append(
                {
                    "slug": page.slug,
                    "kind": page.kind,
                    "sequence": page.sequence,
                    "page_set": page.page_set,
                    "title": page.title,
                    "meta_len": len(page.meta),
                    "word_count": len(page.words),
                    "h2_count": len(page.h2s),
                    "flags": "|".join(page.flags),
                    "protected": "Y" if page.seq_int in PROTECTED_SEQUENCES or page.kind == "CLEARED_PRODUCTION" else "N",
                }
            )

    title_rows = []
    for title, group in sorted(title_clusters.items(), key=lambda item: (-len(item[1]), item[0])):
        title_rows.append(
            {
                "title": title,
                "count": len(group),
                "slugs": " | ".join(page.slug for page in group),
                "kinds": "|".join(sorted({page.kind for page in group})),
            }
        )

    pair_rows = []
    for score, left, right in pairs[:2500]:
        pair_rows.append(
            {
                "jaccard_est": f"{score:.3f}",
                "slug_a": left.slug,
                "slug_b": right.slug,
                "kind_a": left.kind,
                "kind_b": right.kind,
                "title_a": left.title,
                "title_b": right.title,
                "words_a": len(left.words),
                "words_b": len(right.words),
                "protected": "Y"
                if left.kind == "CLEARED_PRODUCTION"
                or right.kind == "CLEARED_PRODUCTION"
                or left.seq_int in PROTECTED_SEQUENCES
                or right.seq_int in PROTECTED_SEQUENCES
                else "N",
            }
        )

    h2_rows = []
    for _, group in sorted(h2_clusters.items(), key=lambda item: -len(item[1]))[:200]:
        h2_rows.append(
            {
                "page_count": len(group),
                "sample_h2s": " || ".join(group[0].h2s[:8]),
                "sample_slugs": " | ".join(page.slug for page in group[:8]),
                "kinds": "|".join(sorted({page.kind for page in group})),
            }
        )

    boiler_rows = [{"page_count": count, "shingle": text} for count, text in boilerplate]
    write_csv(
        out_dir / "page_flags.csv",
        flag_rows,
        ["slug", "kind", "sequence", "page_set", "title", "meta_len", "word_count", "h2_count", "flags", "protected"],
    )
    write_csv(
        out_dir / "duplicate_titles.csv",
        title_rows,
        ["title", "count", "slugs", "kinds"],
    )
    write_csv(
        out_dir / "near_duplicate_pairs.csv",
        pair_rows,
        ["jaccard_est", "slug_a", "slug_b", "kind_a", "kind_b", "title_a", "title_b", "words_a", "words_b", "protected"],
    )
    write_csv(
        out_dir / "h2_skeleton_clusters.csv",
        h2_rows,
        ["page_count", "sample_h2s", "sample_slugs", "kinds"],
    )
    write_csv(out_dir / "boilerplate_shingles.csv", boiler_rows, ["page_count", "shingle"])
    write_csv(
        out_dir / "watermark_cleared_pages.csv",
        watermark_pages,
        ["slug", "kind", "sequence", "token_count", "title"],
    )

    exact_text_dupes = sum(len(group) for group in text_clusters.values())
    summary = {
        "total_pages": n,
        "unique_slugs": len({page.slug for page in pages}),
        "kinds": dict(kinds),
        "store_count": len(stores),
        "wordcount_min": word_counts[0] if word_counts else 0,
        "wordcount_p50": word_counts[n // 2] if word_counts else 0,
        "wordcount_p90": word_counts[9 * n // 10] if word_counts else 0,
        "wordcount_max": word_counts[-1] if word_counts else 0,
        "duplicate_title_groups": len(title_clusters),
        "duplicate_title_pages": sum(len(group) for group in title_clusters.values()),
        "exact_text_duplicate_groups": len(text_clusters),
        "exact_text_duplicate_pages": exact_text_dupes,
        "exact_html_duplicate_groups": len(html_clusters),
        "h2_skeleton_clusters": len(h2_clusters),
        "h2_cluster_pages": sum(len(group) for group in h2_clusters.values()),
        "near_duplicate_pairs": len(pairs),
        "flag_counts": dict(flags),
        "protected_seq_1_5": [page.slug for page in pages if page.seq_int in PROTECTED_SEQUENCES],
        "cleared_pages": kinds.get("CLEARED_PRODUCTION", 0),
        "watermark_cleared_pages": len(watermark_pages),
        "phones_top": phones.most_common(12),
        "slot_h2_top": slot_h2.most_common(20),
    }
    (out_dir / "audit_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    return summary


def write_markdown(summary: dict, out_dir: Path) -> None:
    kinds = "\n".join(f"- {count} `{kind}`" for kind, count in sorted(summary["kinds"].items(), key=lambda item: -item[1]))
    flags = "\n".join(f"- {count} `{flag}`" for flag, count in sorted(summary["flag_counts"].items(), key=lambda item: -item[1])) or "- none"
    seqs = "\n".join(f"- `{slug}`" for slug in summary["protected_seq_1_5"]) or "- none found"
    slots = "\n".join(f"- {count} When {label} deserves a closer look" for label, count in summary["slot_h2_top"])
    phones = "\n".join(f"- {count} `{phone}`" for phone, count in summary["phones_top"]) or "- none"
    md = f"""# ChatGPT uniqueness corpus audit

Audited **{summary['total_pages']}** pages from the 8 `UNIQUENESS_CORPUS_*_OF_08.csv` files.
This report does **not** rewrite pages. `CLEARED_PRODUCTION` and sequences 1–5 stay read-only.

## Inventory

- Unique slugs: {summary['unique_slugs']}
- Stores represented: {summary['store_count']}
- Word count min / median / p90 / max: {summary['wordcount_min']} / {summary['wordcount_p50']} / {summary['wordcount_p90']} / {summary['wordcount_max']}
- CLEARED_PRODUCTION pages: {summary['cleared_pages']} (do not overwrite)
- CLEARED pages with injected watermark tokens: {summary['watermark_cleared_pages']}

### Kinds

{kinds}

### Sequences 1–5 (locked)

{seqs}

## Uniqueness

- Duplicate title groups: **{summary['duplicate_title_groups']}** covering {summary['duplicate_title_pages']} pages
- Exact-text duplicate groups: **{summary['exact_text_duplicate_groups']}** covering {summary['exact_text_duplicate_pages']} pages
- Exact-HTML duplicate groups: **{summary['exact_html_duplicate_groups']}**
- Shared H2-skeleton clusters: **{summary['h2_skeleton_clusters']}** covering {summary['h2_cluster_pages']} pages
- Near-duplicate pairs (MinHash Jaccard ≥ 0.82): **{summary['near_duplicate_pairs']}**

See `near_duplicate_pairs.csv`, `h2_skeleton_clusters.csv`, `duplicate_titles.csv`, and `boilerplate_shingles.csv`.

## Quality / compliance flags

{flags}

Flag detail is in `page_flags.csv`. Watermarked CLEARED pages are listed in `watermark_cleared_pages.csv`.

## Repeated template headings

These H2 slots are reused so often they are no longer unique, and several are ungrammatical (plural noun + “deserves”):

{slots}

## Phone numbers found in HTML

{phones}

## How to reread this on the D: share

```text
python tools/chatgpt_page_audit.py --corpus-dir D:\\CHATGPT_BATCH_INTAKE\\UNIQUENESS_CORPUS --out-dir D:\\Temp\\scr_chatgpt_audit
```

Python can stay on C:; point `--corpus-dir` at the network-shared D: folder that holds the 8 CSV files.
"""
    (out_dir / "AUDIT_SUMMARY.md").write_text(md, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Audit ChatGPT uniqueness-corpus pages")
    parser.add_argument("--corpus-dir", default=None, help="Folder containing the 8 UNIQUENESS_CORPUS CSVs")
    parser.add_argument("--out-dir", default="audit_reports", help="Folder for CSV/JSON/Markdown reports")
    parser.add_argument("--jaccard", type=float, default=0.82, help="Near-duplicate Jaccard threshold")
    args = parser.parse_args()

    corpus_dir = find_corpus_dir(args.corpus_dir)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    print(f"Loading corpus from {corpus_dir}", flush=True)
    pages = load_pages(corpus_dir)
    print(f"Loaded {len(pages)} pages; scoring flags and uniqueness", flush=True)
    flag_pages(pages)
    pairs = near_duplicate_pairs(pages, threshold=args.jaccard)
    boilerplate = frequent_shingles(pages)
    summary = summarize(pages, pairs, boilerplate, out_dir)
    write_markdown(summary, out_dir)
    print(json.dumps({k: summary[k] for k in (
        "total_pages",
        "duplicate_title_groups",
        "exact_text_duplicate_groups",
        "h2_skeleton_clusters",
        "near_duplicate_pairs",
        "flag_counts",
        "watermark_cleared_pages",
    )}, indent=2))
    print(f"Wrote reports to {out_dir.resolve()}")


if __name__ == "__main__":
    main()
